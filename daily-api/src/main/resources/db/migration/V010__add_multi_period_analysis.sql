create table analysis_period_configurations (
  analysis_period varchar(20) primary key,
  enabled boolean not null default true,
  cron_expression varchar(120) not null,
  enabled_modules text not null,
  retention_months integer not null default 24,
  include_evidence_in_delivery boolean not null default false,
  updated_at timestamptz not null default current_timestamp,
  constraint ck_analysis_period_configuration_period
    check (analysis_period in ('DAILY', 'WEEKLY', 'MONTHLY')),
  constraint ck_analysis_period_configuration_retention check (retention_months > 0)
);

