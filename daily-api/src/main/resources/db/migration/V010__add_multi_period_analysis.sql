create table analysis_rule_versions (
  id bigint generated by default as identity primary key,
  analysis_period varchar(20) not null,
  version_number integer not null,
  status varchar(20) not null,
  change_note varchar(1000) not null,
  rules_json text not null,
  prompt_template text not null,
  custom_schema_json text not null default '{}',
  trial_succeeded_at timestamptz,
  published_at timestamptz,
  created_at timestamptz not null default current_timestamp,
  constraint uk_analysis_rule_version unique (analysis_period, version_number),
  constraint ck_analysis_rule_period check (analysis_period in ('DAILY', 'WEEKLY', 'MONTHLY')),
  constraint ck_analysis_rule_status check (status in ('DRAFT', 'PUBLISHED', 'HISTORICAL'))
);

