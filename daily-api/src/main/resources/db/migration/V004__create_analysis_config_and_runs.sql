create table analysis_configurations (
  id smallint primary key,
  enabled boolean not null default true,
  cron_expression varchar(120) not null,
  selected_dimensions varchar(500) not null,
  rule_thresholds text not null,
  prompt_version varchar(80) not null,
  prompt_template text not null,
  dashboard_enabled boolean not null default true,
  report_enabled boolean not null default true,
  email_enabled boolean not null default false,
  recipients text,
  cc_recipients text,
  email_subject_template varchar(300) not null,
  report_template text not null,
  model_endpoint varchar(500),
  model_name varchar(160),
  model_api_key_reference varchar(120) not null default 'LLM_API_KEY',
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp,
  constraint ck_analysis_configuration_singleton check (id = 1)
);

